using Engine.Scripts.VoxelConfig.Data.Internal;
using Engine.Scripts.VoxelConfig.Data.Voxel;
using Engine.Scripts.WorldGen.Settings;
using NUnit.Framework;
using Unity.Collections;
using Unity.Collections.LowLevel.Unsafe;
using Unity.Jobs;
using Unity.Mathematics;
using Unity.PerformanceTesting;
using UnityEngine;
using UnityEngine.Rendering;
using Debug = UnityEngine.Debug;
using Object = UnityEngine.Object;
using Random = Unity.Mathematics.Random;
using static Engine.Scripts.Utils.VoxelConstants;

namespace Engine.Tests.Performance{
    /// <summary>
    ///     Collider mesh per partition on a single worker (CMeshBuildJob.Run). The chunk is generated by
    ///     ChunkJob so the surface partition is realistic; the interior partition is fully solid. The forest row meshes
    ///     the partitions that hold flora of the shipped Forest species (trees, plants) on the terrain they grow on, the
    ///     cave row the partitions that hold caves of the shipped settings, with and without them.
    /// </summary>
    [TestFixture]
    internal class ColliderMeshBenchmark{
        private const int WarmupCount = 3;
        private const int MeasurementCount = 20;

        private static readonly int2 ChunkPos = new(0, 0);

        private readonly List<Object> _created = new();
        private GeneratorConfig _config;
        private NativeParallelHashMap<int2, ChunkVoxelData> _chunks;
        private ChunkAccessor _accessor;
        private NativeArray<VertexAttributeDescriptor> _vertexParams;
        private VoxelEngineRenderGenData _renderGenData;
        private NativeList<int3> _jobs;
        private NativeParallelHashMap<int3, CMeshBuildJob.PartitionJobResult> _results;
        private Mesh.MeshDataArray _meshData;
        private bool _meshDataAllocated;

        [SetUp]
        public void SetUp(){
            _config = BenchmarkFixtures.CreateGeneratorConfig(Allocator.Persistent);

            _chunks = new NativeParallelHashMap<int2, ChunkVoxelData>(1, Allocator.Persistent);
            GenerateChunk();
            _accessor = new ChunkAccessor(_chunks.AsReadOnly());

            _vertexParams = CVertex.CreateLayout(Allocator.Persistent);
            _renderGenData = BenchmarkFixtures.CreateRenderGenData(Allocator.Persistent);
            _jobs = new NativeList<int3>(1, Allocator.Persistent);
            _results = new NativeParallelHashMap<int3, CMeshBuildJob.PartitionJobResult>(ForestChunkCount * PartitionsPerChunk,
                Allocator.Persistent);
        }

        [TearDown]
        public void TearDown(){
            DisposeMeshData();
            _results.Dispose();
            _jobs.Dispose();
            _renderGenData.Dispose();
            _vertexParams.Dispose();
            foreach (KeyValue<int2, ChunkVoxelData> kv in _chunks) kv.Value.Dispose();
            _chunks.Dispose();
            BenchmarkFixtures.DisposeGeneratorConfig(ref _config);
            foreach (Object o in _created) Object.DestroyImmediate(o);
            _created.Clear();
        }

        [Test]
        [Performance]
        public void CMeshBuildJob_Run_SurfacePartition_MsPerPartition(){
            // World y 96..127: the fixture biome puts the surface near y = 100, water level is 124.
            MeasurePartition(new int3(ChunkPos.x, 3, ChunkPos.y), "CMeshBuildJob.Run surface ms/partition");
        }

        [Test]
        [Performance]
        public void CMeshBuildJob_Run_SolidPartition_MsPerPartition(){
            // World y 32..63 is far below the surface: entirely stone, six merged quads.
            MeasurePartition(new int3(ChunkPos.x, 1, ChunkPos.y), "CMeshBuildJob.Run solid ms/partition");
        }

        [Test]
        [Performance]
        public void CMeshBuildJob_Run_AirPartition_MsPerPartition(){
            // World y 224..255 is above every surface: no collision voxels, no quads.
            MeasurePartition(new int3(ChunkPos.x, 7, ChunkPos.y), "CMeshBuildJob.Run air ms/partition");
        }

        private const int ForestChunkCount = 8;

        /// <summary>
        ///     Mean over every partition that holds a species voxel (trunk, crown, plant) in the scattered chunks of the
        ///     DistanceBlend world with the shipped Forest rules on every land biome, so the partitions mesh the
        ///     terrain surface together with the trees and plants of the species. Every flora voxel counts, so a
        ///     partition with only ground plants is in the mean too.
        /// </summary>
        [Test]
        [Performance]
        public void CMeshBuildJob_Run_ForestSpecies_MsPerPartition(){
            GeneratorConfig config = BenchmarkFixtures.CreateSpeciesGeneratorConfig(GenArchitecture.TerrainFirst,
                SpeciesFlora.ShippedForest, Allocator.Persistent, _created, out Dictionary<Voxel, ushort> ids);
            List<int2> centers = GenerateScatteredChunks(ref config, _chunks);

            _accessor = new ChunkAccessor(_chunks.AsReadOnly());
            _renderGenData.Dispose();
            _renderGenData = BenchmarkFixtures.CreateRenderGenData(ids, Allocator.Persistent);

            _jobs.Clear();
            foreach (int2 center in centers)
                for (int py = 0; py < PartitionsPerChunk; py++)
                    if (HasSpeciesVoxel(_chunks[center], py))
                        _jobs.Add(new int3(center.x, py, center.y));
            Assert.Greater(_jobs.Length, 0);
            Debug.Log($"collider forest partitions: {_jobs.Length}");
            MeasurePartitions("CMeshBuildJob.Run forest species ms/partition");
        }

        /// <summary>
        ///     Mean over every partition that holds a cave voxel (air or lava below the column's highest collision voxel)
        ///     in the scattered chunks of the Terrain-first DistanceBlend world with the shipped caves, lava, ores and
        ///     bedrock. Without caves, the same partitions of the same chunks with the cave passes off, so the
        ///     difference is the cost of the cave walls.
        /// </summary>
        [Test]
        [Performance]
        public void CMeshBuildJob_Run_CavePartitions_MsPerPartition([Values(true, false)] bool caves){
            _renderGenData.Dispose();
            _renderGenData = BenchmarkFixtures.CreateCaveRenderGenData(Allocator.Persistent);
            NativeParallelHashMap<int2, ChunkVoxelData> withCaves = new(ForestChunkCount * 9, Allocator.Persistent);
            try{
                GeneratorConfig config = CaveWorld(true);
                List<int2> centers = GenerateScatteredChunks(ref config, withCaves);
                _jobs.Clear();
                foreach (int2 center in centers)
                    for (int py = 0; py < PartitionsPerChunk; py++)
                        if (HasCaveVoxel(withCaves[center], py, _renderGenData))
                            _jobs.Add(new int3(center.x, py, center.y));
                if (caves)
                    foreach (KeyValue<int2, ChunkVoxelData> kv in withCaves){
                        if (!_chunks.TryAdd(kv.Key, kv.Value))
                            kv.Value.Dispose();
                    }
                else{
                    foreach (KeyValue<int2, ChunkVoxelData> kv in withCaves) kv.Value.Dispose();
                    config = CaveWorld(false);
                    GenerateScatteredChunks(ref config, _chunks);
                }
            }
            finally{
                withCaves.Dispose();
            }

            Assert.Greater(_jobs.Length, 0);
            _accessor = new ChunkAccessor(_chunks.AsReadOnly());
            Debug.Log($"collider cave partitions: {_jobs.Length}");
            MeasurePartitions($"CMeshBuildJob.Run cave partitions caves {(caves ? "on" : "off")} ms/partition");

            GeneratorConfig CaveWorld(bool enabled){
                GeneratorConfig c = BenchmarkFixtures.CreatePlaceholderGeneratorConfig(GenArchitecture.TerrainFirst,
                    BlendMethod.DistanceBlend, Allocator.Persistent, _created);
                BenchmarkFixtures.UseShippedCaves(ref c, Allocator.Persistent);
                c.WorldGen.Caves.Enabled = enabled;
                return c;
            }
        }

        /// <summary>
        ///     Generates the scattered chunks of the generation benchmark's per-method rows, each with its 3 × 3 ring, into
        ///     <paramref name="into" /> and returns the centres; disposes <paramref name="config" />.
        /// </summary>
        private static List<int2> GenerateScatteredChunks(ref GeneratorConfig config, NativeParallelHashMap<int2, ChunkVoxelData> into){
            NativeList<int2> generate = new(ForestChunkCount * 9, Allocator.Persistent);
            NativeParallelHashMap<int2, ChunkVoxelData> generated = new(ForestChunkCount * 9, Allocator.Persistent);
            List<int2> centers = new();
            try{
                Random rng = new(42);
                for (int i = 0; i < ForestChunkCount; i++){
                    int2 center = rng.NextInt2(-1000, 1000);
                    centers.Add(center);
                    for (int x = -1; x <= 1; x++)
                    for (int z = -1; z <= 1; z++)
                        generate.Add(center + new int2(x, z));
                }

                new ChunkJob{
                    Jobs = generate,
                    Results = generated.AsParallelWriter(),
                    Config = config
                }.Run(generate.Length);
                foreach (KeyValue<int2, ChunkVoxelData> kv in generated)
                    if (!into.TryAdd(kv.Key, kv.Value))
                        kv.Value.Dispose();
            }
            finally{
                generated.Dispose();
                generate.Dispose();
                BenchmarkFixtures.DisposeGeneratorConfig(ref config);
            }

            return centers;
        }

        /// <summary>True when partition <paramref name="py" /> holds air or lava below its column's highest collision voxel.</summary>
        private static bool HasCaveVoxel(ChunkVoxelData chunk, int py, in VoxelEngineRenderGenData data){
            for (int x = 0; x < ChunkWidth; x++)
            for (int z = 0; z < ChunkDepth; z++){
                int top = -1;
                for (int y = ChunkHeight - 1; y >= 0 && top < 0; y--)
                    if (data.VoxelRenderDefs[chunk.GetVoxel(new int3(x, y, z))].Collision)
                        top = y;
                for (int y = py * PartitionHeight; y < math.min((py + 1) * PartitionHeight, top); y++){
                    ushort v = chunk.GetVoxel(new int3(x, y, z));
                    if (v == BenchmarkFixtures.Air || v == BenchmarkFixtures.CaveLava) return true;
                }
            }

            return false;
        }

        private void MeasurePartitions(string sampleGroup){
            SampleGroup group = new(sampleGroup, SampleUnit.Millisecond);
            for (int i = 0; i < WarmupCount + MeasurementCount; i++){
                _meshData = Mesh.AllocateWritableMeshData(_jobs.Length);
                _meshDataAllocated = true;
                CMeshBuildJob job = new(){
                    ColliderVertexParams = _vertexParams,
                    Accessor = _accessor,
                    Jobs = _jobs,
                    RenderGenData = _renderGenData,
                    Results = _results.AsParallelWriter(),
                    ColliderMeshDataArray = _meshData
                };
                Stopwatch watch = Stopwatch.StartNew();
                job.Run(_jobs.Length);
                watch.Stop();
                DisposeMeshData();
                _results.Clear();
                if (i >= WarmupCount) Measure.Custom(group, watch.Elapsed.TotalMilliseconds / _jobs.Length);
            }
        }

        /// <summary>True when partition <paramref name="py" /> of the chunk holds a voxel above the fixture ids.</summary>
        private static bool HasSpeciesVoxel(ChunkVoxelData chunk, int py){
            for (int y = py * PartitionHeight; y < (py + 1) * PartitionHeight; y++)
            for (int x = 0; x < ChunkWidth; x++)
            for (int z = 0; z < ChunkDepth; z++)
                if (chunk.GetVoxel(new int3(x, y, z)) >= BenchmarkFixtures.VoxelTypeCount)
                    return true;
            return false;
        }

        private void MeasurePartition(int3 partition, string sampleGroup){
            _jobs.Clear();
            _jobs.Add(partition);

            Measure.Method(() => {
                    CMeshBuildJob job = new(){
                        ColliderVertexParams = _vertexParams,
                        Accessor = _accessor,
                        Jobs = _jobs,
                        RenderGenData = _renderGenData,
                        Results = _results.AsParallelWriter(),
                        ColliderMeshDataArray = _meshData
                    };
                    job.Run(_jobs.Length);
                })
                .SampleGroup(new SampleGroup(sampleGroup, SampleUnit.Millisecond))
                .WarmupCount(WarmupCount)
                .MeasurementCount(MeasurementCount)
                .IterationsPerMeasurement(1)
                .SetUp(AllocateMeshData)
                .CleanUp(() => {
                    DisposeMeshData();
                    _results.Clear();
                })
                .Run();
        }

        private void GenerateChunk(){
            NativeList<int2> jobs = new(1, Allocator.TempJob);
            jobs.Add(ChunkPos);
            NativeParallelHashMap<int2, ChunkVoxelData> results = new(1, Allocator.TempJob);
            try{
                ChunkJob job = new(){
                    Jobs = jobs,
                    Results = results.AsParallelWriter(),
                    Config = _config
                };
                job.Run(1);
                _chunks.TryAdd(ChunkPos, results[ChunkPos]);
            }
            finally{
                results.Dispose();
                jobs.Dispose();
            }
        }

        private void AllocateMeshData(){
            _meshData = Mesh.AllocateWritableMeshData(1);
            _meshDataAllocated = true;
        }

        private void DisposeMeshData(){
            if (!_meshDataAllocated) return;
            _meshData.Dispose();
            _meshDataAllocated = false;
        }
    }
}
