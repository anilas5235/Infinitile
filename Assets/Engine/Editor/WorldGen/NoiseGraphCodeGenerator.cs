using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Engine.Scripts.WorldGen.Graph;
using Unity.Mathematics;
using UnityEditor;
using UnityEngine;

namespace Engine.Editor.WorldGen{
    /// <summary>
    ///     Writes C# Burst code for compiled noise graphs: per graph a struct with one method per program and one
    ///     statement per instruction, the values in locals instead of register rows. It calls the interpreter's
    ///     kernels with the same operations in the same order, so it gives the interpreter's values bit for bit. The
    ///     struct carries the graph's code hash and only runs a graph with that hash.
    /// </summary>
    public static class NoiseGraphCodeGenerator{
        /// <summary>The shipped graph's code.</summary>
        public const string ShippedPath = "Assets/Engine/Scripts/WorldGen/Graph/ShippedNoiseGraphCode.cs";

        private const string ShippedNamespace = "Engine.Scripts.WorldGen.Graph";
        private const string ShippedType = "ShippedNoiseGraphCode";
        private const int Lanes = GraphLimits.MaxLanes;

        [MenuItem("Infinitile/Generate Noise Graph Code")]
        private static void WriteShippedMenu(){
            Debug.Log(WriteShipped() ? $"Noise graph code written to {ShippedPath}." : "Noise graph code is up to date.");
        }

        /// <summary>Regenerates the shipped graph's code; true when the file changed.</summary>
        public static bool WriteShipped(){
            string text = GenerateShipped();
            if (File.Exists(ShippedPath) && Normalize(File.ReadAllText(ShippedPath)) == text) return false;
            File.WriteAllText(ShippedPath, text);
            AssetDatabase.ImportAsset(ShippedPath);
            return true;
        }

        /// <summary>Text with "\n" line ends, for comparing a file on disk with generated text.</summary>
        public static string Normalize(string text){
            return text.Replace("\r\n", "\n");
        }

        /// <summary>
        ///     True when the file at <paramref name="path" /> holds <paramref name="expected" />; otherwise writes the
        ///     expected text under Temp and returns that copy's path in <paramref name="freshPath" />.
        /// </summary>
        public static bool IsUpToDate(string path, string expected, out string freshPath){
            freshPath = null;
            if (File.Exists(path) && Normalize(File.ReadAllText(path)) == expected) return true;
            freshPath = Path.Combine("Temp", "GeneratedGraphCode", Path.GetFileName(path));
            Directory.CreateDirectory(Path.GetDirectoryName(freshPath));
            File.WriteAllText(freshPath, expected);
            return false;
        }

        /// <summary>The shipped graph's code. Throws when the graph has errors: code is never made from an invalid graph.</summary>
        public static string GenerateShipped(){
            GraphCompileResult result = ShippedNoiseGraph.Compile();
            if (!result.Succeeded) throw new InvalidOperationException("The noise graph has errors:\n" + string.Join("\n", result.Errors));
            using CompiledNoiseGraph graph = result.Graph;
            return Generate(ShippedNamespace, ShippedNoiseGraph.FileName, (ShippedType, graph));
        }

        /// <summary>One file with a struct per graph, in <paramref name="namespaceName" />; <paramref name="source" /> names the graphs' origin.</summary>
        public static string Generate(string namespaceName, string source, params (string TypeName, CompiledNoiseGraph Graph)[] graphs){
            StringBuilder s = new();
            s.Append("// <auto-generated>\n");
            s.Append($"//     Made by {nameof(NoiseGraphCodeGenerator)} from {source}. Do not edit; regenerate it when the graph changes.\n");
            s.Append("// </auto-generated>\n\n");
            s.Append("using Engine.Scripts.WorldGen.Graph;\n");
            s.Append("using Engine.Scripts.WorldGen.Noise;\n");
            s.Append("using Unity.Jobs;\n");
            s.Append("using Unity.Mathematics;\n\n");
            foreach ((string typeName, CompiledNoiseGraph _) in graphs)
                s.Append($"[assembly: RegisterGenericJobType(typeof(GeneratedRegionJob<{namespaceName}.{typeName}>))]\n");
            s.Append($"\nnamespace {namespaceName}{{\n");
            for (int i = 0; i < graphs.Length; i++){
                if (i > 0) s.Append('\n');
                Type(s, graphs[i].TypeName, graphs[i].Graph);
            }

            s.Append("}\n");
            return s.ToString();
        }

        private static void Type(StringBuilder s, string typeName, CompiledNoiseGraph graph){
            GraphData d = graph.Tables;
            s.Append("    /// <summary>Generated programs of one noise graph; see <see cref=\"IGraphPrograms\" />.</summary>\n");
            s.Append($"    internal unsafe struct {typeName} : IGraphPrograms{{\n");
            s.Append($"        public ulong CodeHash => 0x{graph.CodeHash:X16}UL;\n");
            GraphTableSizes z = graph.Sizes;
            s.Append($"        public GraphTableSizes Sizes => new({z.Instructions}, {z.Programs}, {z.Slots}, {z.Entries}, {z.Octaves}, {z.Points}, {z.Markers});\n\n");
            s.Append("        public void Run(int program, in GraphCode code, float* registers, float* scratch, int lanes, uint seed, ref GraphWorkCounters counters){\n");
            s.Append("            switch (program){\n");
            for (int p = 0; p < d.Programs.Length; p++){
                GraphProgram program = d.Programs[p];
                (long noise2, long noise3) = NoiseOctaves(d, program);
                s.Append($"                case {p}:\n");
                s.Append($"                    {MethodName(program)}(registers, code.Points, lanes, seed);\n");
                s.Append($"                    counters.Instructions += {program.InstructionCount};\n");
                s.Append($"                    counters.InstructionLanes += {program.InstructionCount}L * lanes;\n");
                if (noise2 > 0) s.Append($"                    counters.NoiseSamples2D += {noise2}L * lanes;\n");
                if (noise3 > 0) s.Append($"                    counters.NoiseSamples3D += {noise3}L * lanes;\n");
                s.Append("                    break;\n");
            }

            s.Append("                default:\n");
            s.Append("                    code.Run(code.Programs[program], registers, scratch, lanes, seed, ref counters);\n");
            s.Append("                    break;\n");
            s.Append("            }\n");
            s.Append("        }\n");
            for (int p = 0; p < d.Programs.Length; p++){
                s.Append('\n');
                Program(s, d, d.Programs[p]);
            }

            s.Append("    }\n");
        }

        private static string MethodName(GraphProgram program){
            return program.Stage == GraphStage.Corner ? $"Corner{program.CellHeight}" : program.Stage.ToString();
        }

        private static (long, long) NoiseOctaves(GraphData d, GraphProgram program){
            long noise2 = 0, noise3 = 0;
            for (int i = 0; i < program.InstructionCount; i++){
                GraphInstruction ins = d.Instructions[program.InstructionStart + i];
                if (ins.Op != GraphOp.Noise) continue;
                NoiseEntry e = d.Entries[ins.Aux];
                if (e.Dimensions == 2) noise2 += e.OctaveCount;
                else noise3 += e.OctaveCount;
            }

            return (noise2, noise3);
        }

        /// <summary>The registers an instruction reads, in the interpreter's terms (noise reads x, z and for 3D y).</summary>
        private static IEnumerable<int> Reads(GraphData d, GraphInstruction ins){
            switch (ins.Op){
                case GraphOp.Const:
                    yield break;
                case GraphOp.Noise:
                    yield return 0;
                    if (d.Entries[ins.Aux].Dimensions == 3) yield return 1;
                    yield return 2;
                    if (ins.A >= 0) yield return ins.A;
                    if (ins.B >= 0) yield return ins.B;
                    if (ins.C >= 0) yield return ins.C;
                    yield break;
                case GraphOp.Add:
                case GraphOp.Sub:
                case GraphOp.Mul:
                case GraphOp.Min:
                case GraphOp.Max:
                    yield return ins.A;
                    yield return ins.B;
                    yield break;
                case GraphOp.Lerp:
                case GraphOp.RangeChoice:
                    yield return ins.A;
                    yield return ins.B;
                    yield return ins.C;
                    yield break;
                case GraphOp.Spline:
                    yield return ins.A;
                    for (int j = 0; j < ins.B; j++)
                        if (d.Points[ins.Aux + j].Value >= 0)
                            yield return d.Points[ins.Aux + j].Value;
                    yield break;
                case GraphOp.AddK:
                case GraphOp.SubK:
                case GraphOp.KSub:
                case GraphOp.MulK:
                case GraphOp.MinK:
                case GraphOp.MaxK:
                case GraphOp.Abs:
                case GraphOp.Neg:
                case GraphOp.Square:
                case GraphOp.Cube:
                case GraphOp.HalfNegative:
                case GraphOp.QuarterNegative:
                case GraphOp.SoftClamp:
                case GraphOp.Clamp:
                case GraphOp.Smoothstep:
                case GraphOp.ClampedMap:
                    yield return ins.A;
                    yield break;
                default:
                    throw new InvalidOperationException($"Operation {ins.Op} does not occur in a program.");
            }
        }

        private static void Program(StringBuilder s, GraphData d, GraphProgram program){
            List<GraphInstruction> code = new();
            for (int i = 0; i < program.InstructionCount; i++) code.Add(d.Instructions[program.InstructionStart + i]);
            List<int> outputs = new();
            for (int o = 0; o < program.OutputCount; o++){
                int register = d.Slots[program.OutputStart + o].Register;
                if (!outputs.Contains(register)) outputs.Add(register);
            }

            // Registers read before any write are loaded from their rows at the start of each quad (x, y, z and the
            // inputs); the rest live in locals. Outputs never written (an input passed through) are loaded as well.
            SortedSet<int> loaded = new(), written = new();
            foreach (GraphInstruction ins in code){
                foreach (int r in Reads(d, ins))
                    if (!written.Contains(r))
                        loaded.Add(r);
                written.Add(ins.Dst);
            }

            foreach (int r in outputs)
                if (!written.Contains(r))
                    loaded.Add(r);
            int[] locals = written.Where(r => !loaded.Contains(r)).ToArray();
            int splineValues = code.Where(i => i.Op == GraphOp.Spline).Select(i => (int)i.B).DefaultIfEmpty(0).Max();

            s.Append($"        /// <summary>{program.Stage} program: {program.InstructionCount} instructions, {program.RegisterCount} registers.</summary>\n");
            s.Append($"        private static void {MethodName(program)}(float* r, SplinePoint* points, int lanes, uint seed){{\n");
            s.Append("            int quads = (lanes + 3) >> 2;\n");
            if (splineValues > 0) s.Append($"            float4* sv = stackalloc float4[{splineValues}];\n");
            s.Append("            for (int q = 0; q < quads; q++){\n");
            foreach (int r in loaded) s.Append($"                float4 r{r} = {Row(r)}[q];\n");
            if (locals.Length > 0) s.Append($"                float4 {string.Join(", ", locals.Select(r => $"r{r}"))};\n");
            foreach (GraphInstruction ins in code) Instruction(s, d, ins);
            foreach (int r in outputs) s.Append($"                {Row(r)}[q] = r{r};\n");
            s.Append("            }\n");
            s.Append("        }\n");
        }

        private static string Row(int register){
            return register == 0 ? "((float4*)r)" : $"((float4*)(r + {register * Lanes}))";
        }

        /// <summary>A float constant by its bits, so the code holds exactly the table's value.</summary>
        private static string K(float value){
            return $"math.asfloat(0x{math.asuint(value):X8}u)";
        }

        private static void Instruction(StringBuilder s, GraphData d, GraphInstruction ins){
            string dst = $"r{ins.Dst}", a = $"r{ins.A}", b = $"r{ins.B}", c = $"r{ins.C}";
            const string indent = "                ";
            switch (ins.Op){
                case GraphOp.Const: Line($"{dst} = {K(ins.P0)};"); break;
                case GraphOp.Add: Line($"{dst} = {a} + {b};"); break;
                case GraphOp.Sub: Line($"{dst} = {a} - {b};"); break;
                case GraphOp.Mul: Line($"{dst} = {a} * {b};"); break;
                case GraphOp.Min: Line($"{dst} = math.min({a}, {b});"); break;
                case GraphOp.Max: Line($"{dst} = math.max({a}, {b});"); break;
                case GraphOp.AddK: Line($"{dst} = {a} + {K(ins.P0)};"); break;
                case GraphOp.SubK: Line($"{dst} = {a} - {K(ins.P0)};"); break;
                case GraphOp.KSub: Line($"{dst} = {K(ins.P0)} - {a};"); break;
                case GraphOp.MulK: Line($"{dst} = {a} * {K(ins.P0)};"); break;
                case GraphOp.MinK: Line($"{dst} = math.min({a}, {K(ins.P0)});"); break;
                case GraphOp.MaxK: Line($"{dst} = math.max({a}, {K(ins.P0)});"); break;
                case GraphOp.Abs: Line($"{dst} = math.abs({a});"); break;
                case GraphOp.Neg: Line($"{dst} = -{a};"); break;
                case GraphOp.Square: Line($"{dst} = {a} * {a};"); break;
                case GraphOp.Cube: Line($"{dst} = GraphKernels.Cube({a});"); break;
                case GraphOp.HalfNegative: Line($"{dst} = GraphKernels.HalfNegative({a});"); break;
                case GraphOp.QuarterNegative: Line($"{dst} = GraphKernels.QuarterNegative({a});"); break;
                case GraphOp.SoftClamp: Line($"{dst} = GraphKernels.SoftClamp({a});"); break;
                case GraphOp.Clamp: Line($"{dst} = math.clamp({a}, {K(ins.P0)}, {K(ins.P1)});"); break;
                case GraphOp.Lerp: Line($"{dst} = GraphKernels.Lerp({a}, {b}, {c});"); break;
                case GraphOp.Smoothstep: Line($"{dst} = GraphKernels.Smoothstep({a}, {K(ins.P0)}, {K(ins.P1)});"); break;
                case GraphOp.RangeChoice: Line($"{dst} = GraphKernels.RangeChoice({a}, {b}, {c}, {K(ins.P0)}, {K(ins.P1)});"); break;
                case GraphOp.ClampedMap:
                    Line($"{dst} = GraphKernels.ClampedMap({a}, {K(ins.P0)}, {K(ins.P1)}, {K(ins.P2)}, {K(ins.P3)});");
                    break;
                case GraphOp.Spline:
                    for (int j = 0; j < ins.B; j++){
                        SplinePoint p = d.Points[ins.Aux + j];
                        Line($"sv[{j}] = {(p.Value >= 0 ? $"r{p.Value}" : K(p.Constant))};");
                    }

                    Line($"{dst} = GraphKernels.Spline({a}, points + {ins.Aux}, sv, {ins.B}, {(ins.C != 0 ? "true" : "false")});");
                    break;
                case GraphOp.Noise:
                    Noise(s, d, ins, indent);
                    break;
                default:
                    throw new InvalidOperationException($"Operation {ins.Op} does not occur in a program.");
            }

            void Line(string text){
                s.Append(indent).Append(text).Append('\n');
            }
        }

        /// <summary>
        ///     A noise as the interpreter samples it: coordinates shifted by the offset registers, then per octave
        ///     acc + n · amp (ridged: acc + (1 − |n|) · amp) from zero, the coordinates times the octave's frequency.
        /// </summary>
        private static void Noise(StringBuilder s, GraphData d, GraphInstruction ins, string indent){
            NoiseEntry e = d.Entries[ins.Aux];
            bool is3D = e.Dimensions == 3;
            string x = ins.A >= 0 ? $"r0 + r{ins.A}" : "r0";
            string y = ins.B >= 0 ? $"r1 + r{ins.B}" : "r1";
            string z = ins.C >= 0 ? $"r2 + r{ins.C}" : "r2";
            s.Append(indent).Append("{\n");
            string inner = indent + "    ";
            s.Append(inner).Append(is3D ? $"float4 nx = {x}, ny = {y}, nz = {z};\n" : $"float4 nx = {x}, nz = {z};\n");
            s.Append(inner).Append("float4 n = float4.zero;\n");
            for (int o = 0; o < e.OctaveCount; o++){
                NoiseOctave oct = d.Octaves[e.OctaveStart + o];
                string fxz = K(oct.FrequencyXZ);
                string sample = is3D
                    ? $"SimplexLanes.Noise3(nx * {fxz}, ny * {K(oct.FrequencyY)}, nz * {fxz}, seed, 0x{oct.Salt:X8}u)"
                    : $"SimplexLanes.Noise2(nx * {fxz}, nz * {fxz}, seed, 0x{oct.Salt:X8}u)";
                string term = e.Mode == NoiseMode.Ridged ? $"(1f - math.abs({sample}))" : sample;
                s.Append(inner).Append($"n = n + {term} * {K(oct.Amplitude)};\n");
            }

            s.Append(inner).Append($"r{ins.Dst} = n;\n");
            s.Append(indent).Append("}\n");
        }
    }
}
